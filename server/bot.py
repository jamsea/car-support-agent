"""car-support-agent - Pipecat Voice Agent

This bot uses a cascade pipeline: Speech-to-Text → LLM → Text-to-Speech

Generated by Pipecat CLI

The conversation is a Pipecat Flow. The graph is in flow.yaml and its one
tool is in handlers.py.

Required AI services:
- Deepgram Nova-3, Australian English (Speech-to-Text)
- OpenAI, or phoneLLM mini hosted by Deepgram (LLM)
- Deepgram Flux TTS, Australian voice (Text-to-Speech)

Run the bot using::

    uv run bot.py
"""

import os
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

from dotenv import load_dotenv
from loguru import logger
from pipecat.audio.vad.silero import SileroVADAnalyzer
from pipecat.evals.transport import EvalTransportParams
from pipecat.flows import Flow, FlowConfig, FlowManager
from pipecat.pipeline.pipeline import Pipeline
from pipecat.pipeline.worker import PipelineParams, PipelineWorker
from pipecat.processors.aggregators.llm_context import LLMContext
from pipecat.processors.aggregators.llm_response_universal import (
    AssistantTurnStoppedMessage,
    LLMContextAggregatorPair,
    LLMUserAggregatorParams,
    UserTurnStoppedMessage,
)
from pipecat.runner.types import RunnerArguments
from pipecat.runner.utils import create_transport
from pipecat.services.deepgram.flux.tts import DeepgramFluxTTSService
from pipecat.services.deepgram.stt import DeepgramSTTService
from pipecat.services.openai.llm import OpenAILLMService
from pipecat.transcriptions.language import Language
from pipecat.transports.base_transport import BaseTransport, TransportParams
from pipecat.transports.daily.transport import DailyParams
from pipecat.turns.wait_reassurance.llm_extension import WaitReassuranceLLMExtension
from pipecat.workers.runner import WorkerRunner

import handlers
from deepgram_llm import DeepgramLLMService

load_dotenv(override=True)

FLOW_CONFIG_PATH = Path(__file__).with_name("flow.yaml")

# The store's time zone, used to tell the LLM the date and time of the call.
STORE_TIMEZONE = ZoneInfo(os.getenv("STORE_TIMEZONE") or "Australia/Sydney")


async def run_bot(transport: BaseTransport, llm_choice: str = "openai"):
    """Main bot logic."""
    logger.info("Starting bot")

    # Speech-to-Text service
    stt = DeepgramSTTService(
        api_key=os.getenv("DEEPGRAM_API_KEY"),
        settings=DeepgramSTTService.Settings(
            model="nova-3-general",
            language=Language.EN_AU,
        ),
    )

    # Text-to-Speech service
    tts = DeepgramFluxTTSService(
        api_key=os.getenv("DEEPGRAM_API_KEY"),
        settings=DeepgramFluxTTSService.Settings(
            # flux-sharon-en is the Australian Flux TTS voice
            voice=os.getenv("DEEPGRAM_VOICE_ID") or "flux-sharon-en",
            language=Language.EN_AU,
            # A bit faster than the default pace. Range is 0.5 to 1.5, in steps of 0.05.
            speed=1.15,
        ),
    )

    # LLM service
    # While a slow tool call is running (check_booking_hold in handlers.py) and
    # nothing has been said for a few seconds, the LLM says a short "still
    # checking" line, or chooses to stay quiet.
    wait_reassurance = WaitReassuranceLLMExtension(interval_secs=6.0)

    if llm_choice == "phonellm":
        # phoneLLM mini, hosted by Deepgram. Uses the Deepgram API key.
        llm = DeepgramLLMService(
            api_key=os.getenv("DEEPGRAM_API_KEY"),
            settings=DeepgramLLMService.Settings(extensions=[wait_reassurance]),
        )
    else:
        llm = OpenAILLMService(
            api_key=os.getenv("OPENAI_API_KEY"),
            settings=OpenAILLMService.Settings(
                model=os.getenv("OPENAI_MODEL") or "gpt-4.1",
                extensions=[wait_reassurance],
            ),
        )
    logger.info(f"LLM: {llm_choice}")

    # No user_turn_strategies here, so Pipecat's defaults apply: VAD starts a turn
    # and the local smart-turn model ends it.
    context = LLMContext()
    context_aggregator = LLMContextAggregatorPair(
        context,
        user_params=LLMUserAggregatorParams(vad_analyzer=SileroVADAnalyzer()),
    )
    user_aggregator = context_aggregator.user()
    assistant_aggregator = context_aggregator.assistant()

    # Pipeline - assembled from reusable components
    pipeline = Pipeline(
        [
            transport.input(),
            stt,
            user_aggregator,
            llm,
            tts,
            transport.output(),
            assistant_aggregator,
        ]
    )

    worker = PipelineWorker(
        pipeline,
        params=PipelineParams(
            enable_metrics=True,
            enable_usage_metrics=True,
        ),
        observers=[],
    )

    # The flow is data: load it, then join it to the tool it names.
    flow = Flow(FlowConfig.from_file(FLOW_CONFIG_PATH), handlers=handlers)

    flow_manager = FlowManager(
        worker=worker,
        llm=llm,
        context_aggregator=context_aggregator,
        transport=transport,
        global_functions=flow.global_functions,
    )

    @worker.rtvi.event_handler("on_client_ready")
    async def on_client_ready(rtvi):
        # Kick off the conversation at the first node of the flow
        # flow.yaml's role_message refers to this as {{ call_started_at }}.
        now = datetime.now(STORE_TIMEZONE)
        flow_manager.state["call_started_at"] = now.strftime("%A %d %B %Y at %I:%M %p")
        await flow_manager.initialize(flow.initial_node)

    @transport.event_handler("on_client_connected")
    async def on_client_connected(transport, client):
        logger.info("Client connected")

    @transport.event_handler("on_client_disconnected")
    async def on_client_disconnected(transport, client):
        logger.info("Client disconnected")
        await worker.cancel()

    @user_aggregator.event_handler("on_user_turn_stopped")
    async def on_user_turn_stopped(aggregator, strategy, message: UserTurnStoppedMessage):
        timestamp = f"[{message.timestamp}] " if message.timestamp else ""
        line = f"{timestamp}user: {message.content}"
        logger.info(f"Transcript: {line}")

    @assistant_aggregator.event_handler("on_assistant_turn_stopped")
    async def on_assistant_turn_stopped(aggregator, message: AssistantTurnStoppedMessage):
        timestamp = f"[{message.timestamp}] " if message.timestamp else ""
        line = f"{timestamp}assistant: {message.content}"
        logger.info(f"Transcript: {line}")

    runner = WorkerRunner(handle_sigint=False)

    await runner.add_workers(worker)
    await runner.run()


async def bot(runner_args: RunnerArguments):
    """Main bot entry point."""
    # Krisp is available when deployed to Pipecat Cloud
    if os.environ.get("ENV") != "local":
        from pipecat.audio.filters.krisp_viva_filter import KrispVivaFilter

        krisp_filter = KrispVivaFilter()
    else:
        krisp_filter = None

    transport_params = {
        "daily": lambda: DailyParams(
            audio_in_enabled=True,
            audio_in_filter=krisp_filter,
            audio_out_enabled=True,
        ),
        "webrtc": lambda: TransportParams(
            audio_in_enabled=True,
            audio_in_filter=krisp_filter,
            audio_out_enabled=True,
        ),
        # Lets `pipecat eval` drive this bot. See evals/.
        "eval": lambda: EvalTransportParams(
            audio_in_enabled=True,
            audio_out_enabled=True,
        ),
    }

    transport = await create_transport(runner_args, transport_params)
    # The web client sends {"llm": "openai" | "phonellm"} in the start request.
    # LLM_SERVICE sets the default, which is also what the evals use.
    body = runner_args.body if isinstance(runner_args.body, dict) else {}
    llm_choice = body.get("llm") or os.getenv("LLM_SERVICE") or "openai"

    await run_bot(transport, llm_choice)


if __name__ == "__main__":
    from pipecat.runner.run import main

    main()
